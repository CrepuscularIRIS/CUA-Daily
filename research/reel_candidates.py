"""Pick Reel candidates from the board and look up each paper's arXiv license → reel/candidates.md (+ .jsonl).

A Reel poster/video reuses the paper's figures. Only CC BY / CC BY-SA / CC0 allow that on a public repo; arXiv's default
license (no <license> tag) and NC/ND licenses mean: redraw figures or link instead of embedding.

Usage: python research/reel_candidates.py [--min-score 60]
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from net import get  # noqa: E402  (≥3 s pacing, 429 → Retry-After once, then stop)

OAI = "https://export.arxiv.org/oai2?verb=GetRecord&identifier=oai:arXiv.org:{id}&metadataPrefix=arXivRaw"
REUSE_OK = re.compile(r"creativecommons\.org/(licenses/by/|licenses/by-sa/|publicdomain/zero/)")


def license_of(aid: str) -> str:
    m = re.search(r"<license>([^<]+)</license>", get(OAI.format(id=aid)).decode("utf-8", "ignore"))
    return m.group(1).strip() if m else "arxiv-default"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-score", type=int, default=60)
    args = ap.parse_args()
    meta = {r["arxiv"]: r for r in map(json.loads, Path("research/corpus.jsonl").read_text().splitlines())}
    scores = [json.loads(l) for l in Path("research/scores.jsonl").read_text().splitlines()]
    picked = sorted((s for s in scores if s["total"] >= args.min_score and not s.get("abstract_only")), key=lambda s: (-s["total"], s["arxiv"]))
    out = Path("reel")
    out.mkdir(exist_ok=True)
    cache = {r["arxiv"]: r for r in map(json.loads, (out / "candidates.jsonl").read_text().splitlines())} if (out / "candidates.jsonl").exists() else {}
    rows = []
    for s in picked:
        lic = cache.get(s["arxiv"], {}).get("license")
        if lic is None:
            lic = license_of(s["arxiv"])
        rows.append({"arxiv": s["arxiv"], "version": meta[s["arxiv"]]["latest_version"], "title": meta[s["arxiv"]]["title"],
                     "score": s["total"], "band": s["band"], "sub_pattern": s["sub_pattern"], "code_url": s.get("code_url"),
                     "license": lic, "figure_reuse": bool(REUSE_OK.search(lic)), "status": cache.get(s["arxiv"], {}).get("status", "todo")})
    (out / "candidates.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    ok = sum(r["figure_reuse"] for r in rows)
    md = [f"# Reel candidates (score ≥ {args.min_score})", "",
          f"{len(rows)} papers; {ok} allow figure reuse (CC BY / BY-SA / CC0). For the rest, redraw figures or link to the paper.",
          "Generated by `research/reel_candidates.py`; `status` is updated by the Reel run.", "",
          "| # | Paper | Score | Pattern | Code | License | Figures | Status |", "|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        lic = ("arXiv default" if "nonexclusive-distrib" in r["license"] or r["license"] == "arxiv-default"
               else r["license"].replace("http://creativecommons.org/licenses/", "CC ").rstrip("/").upper().replace("CC ", "CC-"))
        md.append(f"| {i} | [{r['title'][:80]}](https://arxiv.org/abs/{r['version']}) | {r['score']} {r['band']} | "
                  f"[{r['sub_pattern']}](../patterns/sub/{r['sub_pattern']}.md) | {'[code](' + r['code_url'] + ')' if r['code_url'] else '—'} | "
                  f"{lic} | {'reuse' if r['figure_reuse'] else 'redraw'} | {r['status']} |")
    (out / "candidates.md").write_text("\n".join(md) + "\n")
    print(f"{len(rows)} candidates, {ok} allow figure reuse → reel/candidates.md")


if __name__ == "__main__":
    assert REUSE_OK.search("http://creativecommons.org/licenses/by/4.0/") and not REUSE_OK.search("http://creativecommons.org/licenses/by-nc-sa/4.0/")
    main()
